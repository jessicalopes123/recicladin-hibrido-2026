create or replace function public.delete_material_preserving_history(p_material_id bigint)
returns void
language plpgsql
security invoker
set search_path = public
as $$
begin
  if public.my_role() <> 'admin' then
    raise exception 'Only administrators can delete materials.';
  end if;

  update public.weighings set material_id = null where material_id = p_material_id;
  update public.orders set material_id = null where material_id = p_material_id;
  delete from public.materials where id = p_material_id;
  if not found then
    raise exception 'Material not found.';
  end if;
end;
$$;

revoke all on function public.delete_material_preserving_history(bigint) from public, anon;
grant execute on function public.delete_material_preserving_history(bigint) to authenticated;

do $$
declare
  table_name text;
  sequence_name text;
begin
  foreach table_name in array array[
    'materials', 'collections', 'weighings', 'oil_collections',
    'green_wallet', 'benefits', 'benefit_redemptions'
  ] loop
    sequence_name := pg_get_serial_sequence(format('public.%I', table_name), 'id');
    if sequence_name is not null then
      execute format('grant usage, select on sequence %s to authenticated', sequence_name);
    end if;
  end loop;
end;
$$;


  add column if not exists role text not null default 'partner',
  add column if not exists avatar_url text,
  add column if not exists background_url text,
  add column if not exists channel_email boolean not null default true,
  add column if not exists channel_whatsapp boolean not null default false,
  add column if not exists notification_frequency text not null default 'por_evento',
  add column if not exists accepted_terms_at timestamptz;

create table if not exists public.materials (
  id bigint generated by default as identity primary key,
  name text not null unique,
  unit text not null default 'kg',
  reference_price numeric(10,2) not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.collections (
  id bigint generated by default as identity primary key,
  partner_id uuid not null references public.profiles(id) on delete cascade,
  type text not null,
  requested_date date not null,
  status text not null default 'solicitada',
  notes text,
  created_at timestamptz not null default now()
);

create table if not exists public.weighings (
  id bigint generated by default as identity primary key,
  partner_id uuid not null references public.profiles(id) on delete cascade,
  material_id bigint references public.materials(id) on delete set null,
  material_name text not null,
  total_kg numeric(12,3) not null default 0,
  points numeric(12,2) not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.oil_collections (
  id bigint generated by default as identity primary key,
  partner_id uuid not null references public.profiles(id) on delete cascade,
  liters numeric(12,2) not null default 0,
  status text not null default 'registrado',
  created_at timestamptz not null default now()
);

create table if not exists public.green_wallet (
  id bigint generated by default as identity primary key,
  partner_id uuid not null unique references public.profiles(id) on delete cascade,
  points_balance numeric(12,2) not null default 0,
  updated_at timestamptz not null default now()
);

create table if not exists public.benefits (
  id bigint generated by default as identity primary key,
  name text not null,
  description text,
  points_cost numeric(12,2) not null,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.benefit_redemptions (
  id bigint generated by default as identity primary key,
  partner_id uuid not null references public.profiles(id) on delete cascade,
  benefit_id bigint not null references public.benefits(id) on delete restrict,
  points_used numeric(12,2) not null,
  status text not null default 'solicitado',
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  buyer_id uuid not null references public.profiles(id) on delete cascade,
  material_id bigint references public.materials(id) on delete set null,
  quantity_kg numeric(12,3) not null default 0,
  status text not null default 'solicitado',
  created_at timestamptz not null default now()
);

